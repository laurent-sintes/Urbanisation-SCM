import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const app = path.dirname(fileURLToPath(import.meta.url));
export const catalogs = Object.fromEntries(
  ['ui', 'core', 'server', 'export', 'bootstrap'].map((name) => [
    name,
    JSON.parse(fs.readFileSync(path.join(app, `locales/fr/${name}.json`), 'utf8')),
  ]),
);
export const messages = {};
for (const catalog of Object.values(catalogs)) {
  for (const [key, value] of Object.entries(catalog)) {
    if (Object.hasOwn(messages, key)) throw new Error(`Duplicate resource: ${key}`);
    messages[key] = value;
  }
}

export function parameters(template) {
  if (template && typeof template === 'object') {
    if (typeof template.one !== 'string' || typeof template.other !== 'string')
      throw new Error('Invalid plural resource');
    return [...new Set(['count', ...parameters(template.one), ...parameters(template.other)])];
  }
  return [
    ...new Set([...template.matchAll(/\{\{|\}\}|\{([\w$]+)\}/g)].flatMap((match) => (match[1] ? [match[1]] : []))),
  ];
}

export function schema() {
  const entries = Object.entries(messages).map(([key, value]) => {
    if (typeof value !== 'string' && (!value || typeof value !== 'object'))
      throw new Error(`Invalid text resource: ${key}`);
    const fields = parameters(value)
      .map(
        (parameter) =>
          `${JSON.stringify(parameter)}: ${parameter === 'count' && typeof value === 'object' ? 'number' : 'unknown'};`,
      )
      .join(' ');
    return `  ${JSON.stringify(key)}: { ${fields} };`;
  });
  return `// Generated by label-resources.mjs --write. Do not edit.\nexport interface UiArguments {\n${entries.join('\n')}\n}\n`;
}

if (process.argv.includes('--write')) fs.writeFileSync(path.join(app, 'src/ui-schema.d.ts'), schema());
