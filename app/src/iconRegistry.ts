const typeIcons: Record<string, LucideIcon> = {
  universe: Layers,
  business_system: Network,
  domain: Boxes,
  area: Boxes,
  business_area: Boxes,
  capability: Workflow,
  behavior: ListFilter,
  reference: BookOpen,
  group: FolderTree,
  object: Box,
  document: FileText,
  event: Zap,
};
export function iconFor(node: AtlasNode): LucideIcon {
  const explicit = node.reading?.icon && iconRegistry[node.reading.icon];
  if (explicit) return explicit;
  if (node.kind === 'behavior') {
    const nature = behaviorNature(node);
    const icons: Record<string, LucideIcon> = {
      SlidersHorizontal,
      Route,
      Settings2,
      ScanLine,
      Compass,
      ArrowLeftRight,
      CalendarCheck,
    };
    return nature ? icons[behaviorTypes[nature].icon] : ListFilter;
  }
  if (node.kind === 'capability') {
    const nature = capabilityNature(node);
    const icons: Record<(typeof capabilityTypes)[CapabilityNature]['icon'], LucideIcon> = {
      Zap,
      SlidersHorizontal,
      Eye,
      Workflow,
      CalendarCheck,
      ShieldCheck,
      GitBranch,
      ArrowLeftRight,
      BookOpen,
      Calculator,
    };
    return nature ? icons[capabilityTypes[nature].icon] : Box;
  }
  return (node.groupRole === 'urbanism_level' ? Layers : typeIcons[node.kind]) ?? Box;
}
